let mi = 0;
let comfort = false;
let sel = new Set();

const money = n => n.toLocaleString('ru-RU') + ' ₽';


const sizes = document.querySelector('#sizes');
M.forEach((m, i) => {
  const tile = document.createElement('button');
  tile.className = 'size';
  tile.innerHTML = `<b>${m[0]} м</b><span class="size-price"></span>`;
  tile.onclick = () => {
    mi = i;
    render();
  };
  sizes.appendChild(tile);
});

const grid = document.querySelector('#optionsGrid');

O.forEach((o, i) => {
    const element = document.createElement('div');
    element.className = 'option';
    element.innerHTML = `
        <img src="assets/catalog-${o[3]}.jpg">
        <div>
            <h3>${o[0]}</h3>
            <p>${o[1]}</p>
            <div class="oprice">${o[2] ? money(o[2]) : '10% к стоимости'}</div>
        </div>
    `;

    element.onclick = () => {
        if (sel.has(i)) {
            sel.delete(i);
        } else {
            sel.add(i);
        }

        element.classList.toggle('selected', sel.has(i));
        calc();
    };

    grid.appendChild(element);
});

function render() {
    const m = M[mi];

    document.querySelectorAll('.size').forEach((tile, i) => {
        tile.classList.toggle('active', i === mi);
        tile.querySelector('.size-price').textContent = 'от ' + money(comfort ? M[i][4] : M[i][3]);
    });

    document.querySelector('#modelImg').src = `assets/model-${mi + 1}.jpg`;
    document.querySelector('#badge').textContent = `КВАДРО-БАНЯ · ${m[0]} м`;
    document.querySelector('#title').textContent = `Квадро-баня ${m[0]} м`;
    document.querySelector('#sub').textContent = `${m[1]} ${m[1] === 1 ? 'секция' : 'секции'} · ${m[2]}`;

    document.querySelector('#specs').innerHTML = [
        ['Габариты база', m[5]],
        ['Габариты комфорт', m[6]],
        ['Размер парной', m[7]],
        ['Размер помывочной', m[8]],
        ['Комната отдыха', m[9]],
        ['Вес', m[10]],
    ].map(x => `
        <div class="spec">
            <small>${x[0]}</small>
            <strong>${x[1]}</strong>
        </div>
    `).join('');

    document.querySelector('#base').classList.toggle('active', !comfort);
    document.querySelector('#comfort').classList.toggle('active', comfort);
    document.querySelector('#pack').textContent = comfort ? 'КОМПЛЕКТАЦИЯ КОМФОРТ' : 'БАЗОВАЯ КОМПЛЕКТАЦИЯ';
    document.querySelector('#price').textContent = money(comfort ? m[4] : m[3]);

    document.querySelector('#features').innerHTML = (comfort ? m[12] : m[11])
        .map(x => `<li>${x}</li>`)
        .join('');

    calc();
}

document.querySelector('#base').onclick = () => {
    comfort = false;
    render();
};

document.querySelector('#comfort').onclick = () => {
    comfort = true;
    render();
};

function calc() {
    const m = M[mi];
    let total = comfort ? m[4] : m[3];

    sel.forEach(i => {
        const price = O[i][2];
        total = price ? total + price : Math.round(total * 1.1);
    });

    document.querySelector('#total').textContent = money(total);
    document.querySelector('#summary').textContent = `${m[0]} м · ${comfort ? 'Комфорт' : 'База'} · опций: ${sel.size}`;
    document.querySelector('#contactConfig').textContent = `Квадро-баня ${m[0]} м · ${comfort ? 'Комфорт' : 'База'} · опций: ${sel.size} · ${money(total)}`;
}

render();
// ===== кнопка "наверх" =====
const toTop = document.querySelector('#toTop');
if (toTop) {
  window.addEventListener('scroll', () => {
    toTop.classList.toggle('show', window.scrollY > 500);
  });
  toTop.onclick = () => window.scrollTo({ top: 0, behavior: 'smooth' });
}

// ===== переключение темы =====
const themeBtn = document.querySelector('#themeBtn');
if (themeBtn) {
  try {
    if (localStorage.getItem('theme') === 'light') {
      document.body.classList.add('light');
    }
  } catch (e) {}

  const themeIcon = () => {
    themeBtn.textContent = document.body.classList.contains('light') ? '🌙' : '☀️';
  };
  themeIcon();

  themeBtn.onclick = () => {
    const isLight = document.body.classList.toggle('light');
    try { localStorage.setItem('theme', isLight ? 'light' : 'dark'); } catch (e) {}
    themeIcon();
  };
}